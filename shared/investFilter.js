const has = (text, words) => words.some((w) => text.includes(w));

/**
 * @param {unknown} text 사용자 입력
 * @returns {{blocked: boolean, reason?: 'always' | 'action' | 'forecast'}}
 */
export function checkInvestAdvice(text) {
  const t = String(text ?? '').toLowerCase().replace(/\s+/g, ' ');
  if (has(t, ALWAYS)) return { blocked: true, reason: 'always' };
  const asset = has(t, ASSET) || ASSET_PATTERNS.some((p) => p.test(t));
  if (asset && has(t, ACTION)) return { blocked: true, reason: 'action' };
  if (asset && has(t, FORECAST)) return { blocked: true, reason: 'forecast' };
  return { blocked: false };
}

