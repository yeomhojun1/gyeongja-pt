export const DEMO_UNKNOWN =
  '지금은 미리 준비한 예시 질문만 답할 수 있습니다.\n아래 예시 질문 중 하나를 눌러 보세요.';

const normalize = (s) => s.toLowerCase().replace(/[\s?？.!,()（）·]/g, '');

/**
 * 질문에 맞는 미리 쓴 답을 찾는다. 질문 문장이 같으면 그 답, 아니면 키워드 묶음이 모두 들어 있는 것 중
 * 가장 구체적인(키워드가 많은) 묶음을 가진 답. 같으면 목록 앞쪽. 없으면 null.
 */
export function findDemoAnswer(text) {
  const t = normalize(text);
  if (!t) return null;
  const exact = DEMO_QA.find((qa) => normalize(qa.question) === t);
  if (exact) return exact.answer;
  let best = null;
  let bestScore = 0;
  for (const qa of DEMO_QA) {
    for (const group of qa.keywords) {
      if (group.length > bestScore && group.every((k) => t.includes(normalize(k)))) {
        best = qa;
        bestScore = group.length;
      }
    }
  }
  return best ? best.answer : null;
}
