const norm = (s) => String(s).toLowerCase().replace(/\s+/g, '');

/** 주제 문자열에 맞는 미리 쓴 비교를 찾는다. 없으면 null */
export function findCompareTopic(text) {
  const t = norm(text);
  return COMPARE_TOPICS.find((c) => norm(c.title) === t || c.keywords.some((k) => t.includes(norm(k)))) || null;
}
